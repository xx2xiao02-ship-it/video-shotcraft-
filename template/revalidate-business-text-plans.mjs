import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {validateGlobalPlan,validateShotPlan,buildStoryboard} from '../director/a-mode-run.mjs';
import {fitVideoPlayback} from '../director/video-material-policy.mjs';

const root=path.resolve(import.meta.dirname,'..'),batch=process.argv[2];
if(!/^card-business-text-batch\d+(?:-v\d+)?$/.test(batch || '')) throw new Error('Isolated batch required');
const read=file=>JSON.parse(fs.readFileSync(path.resolve(root,file),'utf8'));
const hash=file=>crypto.createHash('sha256').update(fs.readFileSync(path.resolve(root,file))).digest('hex');
const file=`template/out/${batch}/acceptance.json`,report=read(file);
const snapshot=`template/out/${batch}/acceptance-before-plan-repair.json`;
if(fs.existsSync(path.resolve(root,snapshot))) throw new Error('Prior revision is preserved; select a fresh evidence batch');
const planOnly=new Set(['director/a-mode-run.mjs','director/a-mode-render-preflight.mjs','director/text-card-contracts.mjs']);
const changed=[];
for(const [source,sha] of Object.entries(report.sourceHashes)){
  if(hash(source)===sha) continue;
  assert.equal(planOnly.has(source),true,'Render/evidence dependency changed: '+source);
  changed.push({file:source,before:sha,after:hash(source)});
}
assert.ok(changed.length>0,'A real plan revision is required');
const fixture=read(report.fixtureFile),original=read('director/a-mode-runs/f4f78a6c-aa2b-4917-9bed-66398863f3f9/props.json');
if(fixture.baselineFixture) fixture.cards=[...read(fixture.baselineFixture).cards,...fixture.cards];
assert.equal(report.cases.length,fixture.cards.length*2);
for(const item of report.cases){
  assert.equal(item.error,undefined);assert.equal(item.video?.fullDecodePassed,true);
  assert.equal(hash(item.video.file),item.video.sha256);assert.equal(hash(item.propsFile),item.propsSha256);
  for(const sample of item.samples) assert.equal(hash(sample.file),sample.sha256);
  const previous=read(item.propsFile),shot=previous.storyboard.shots[0];
  const segments=[{text:shot.text,fromFrame:0,durationInFrames:180}];
  const global={fromSegment:0,toSegment:1,type:shot.type,card:shot.shotCard,material:shot.material,materialRole:shot.materialRole,reason:shot.direction};
  const globals=validateGlobalPlan({shots:[global]},segments,[{path:shot.material,duration_sec:report.media.durationSeconds}],
    {requireBackground:true,availableCards:fixture.cards.map(card=>card.id)});
  const details=validateShotPlan({shots:[{index:0,displayLines:shot.displayLines,elementPlan:shot.elementPlan,captionHighlights:['']}]},globals,segments);
  const storyboard=buildStoryboard(root,'00000000-0000-4000-8000-000000000004',{fps:30,totalFrames:180,segments},globals,details,
    {...read('director/current-theme.json'),aspectRatio:item.aspect});
  storyboard.shots[0].materialPlayback=fitVideoPlayback(report.media.durationSeconds,180,30);
  const props={...original,bgm:null,storyboard:{...storyboard,style:original.storyboard.style,theme:original.storyboard.theme,
    audio:undefined,subtitleHighlights:undefined,subtitleV1:undefined}};
  assert.deepEqual(JSON.parse(JSON.stringify(props)),previous,'Planner changed the actual render input: '+item.card+'/'+item.aspect);
}
fs.copyFileSync(path.resolve(root,file),path.resolve(root,snapshot));
report.planCompatibility={previousReport:snapshot,previousReportSha256:hash(snapshot),changedPlanningSources:changed,
  casesRevalidated:report.cases.length,exactRenderPropsPreserved:true,rendererDependenciesUnchanged:true,
  scope:'All authored 180-frame business plans regenerated by current validators/buildStoryboard; independently rendered artifacts retain their unchanged exact inputs. No new short-form admission.'};
for(const change of changed) report.sourceHashes[change.file]=change.after;
report.sourceHashes['template/revalidate-business-text-plans.mjs']=hash('template/revalidate-business-text-plans.mjs');
report.sourceHashes[snapshot]=hash(snapshot);
report.sourceConsistency=true;
fs.writeFileSync(path.resolve(root,file),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report.planCompatibility));
